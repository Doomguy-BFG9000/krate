#!/usr/bin/env python3
"""Write crates/gpu-names/src/lib.rs from wgpu-types' own WebGPU name tables.

krate:gpu passes texture formats, vertex formats, features and limits as
WebGPU's names. wgpu-types knows those names only behind its serde feature,
so this reads them out of its source and writes plain match tables that the
host and the guest backend both link.

    python3 scripts/gen-gpu-names.py            # write the file
    python3 scripts/gen-gpu-names.py --check    # fail if it is not what this writes

Run it after moving the workspace to a new wgpu-types version; the versions
are read from crates/gpu-names/Cargo.toml.
"""
import glob
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TARGET = os.path.join(ROOT, "crates/gpu-names/src/lib.rs")
CHECK = "--check" in sys.argv
# The versions crates/gpu-names itself depends on: `wgt` (the workspace's,
# what the host links) and `wgt27`.
MANIFEST = open(os.path.join(ROOT, "crates/gpu-names/Cargo.toml")).read()
VERSION = re.search(r'^wgt = \{ package = "wgpu-types", version = "([^"]+)"', MANIFEST, re.M).group(1)


def source(version):
    found = glob.glob(os.path.expanduser("~/.cargo/registry/src/*/wgpu-types-%s/src" % version))
    if not found:
        sys.exit("wgpu-types %s is not in the cargo registry: run cargo fetch" % version)
    return found[0]


def part(WGT, name):
    """A wgpu-types source file; older versions keep everything in lib.rs."""
    path = os.path.join(WGT, name)
    return open(path if os.path.exists(path) else os.path.join(WGT, "lib.rs")).read()


# wgpu 28 renamed push constants to immediates (and the primitive index
# feature): an older version's flag or limit goes by the name the host knows,
# so a wgpu 27 program asking for push constants is given immediates, which
# are the same thing.
OLDER_FEATURE = {"IMMEDIATES": "PUSH_CONSTANTS", "PRIMITIVE_INDEX": "SHADER_PRIMITIVE_INDEX"}
NEWER_LIMIT = {"max_push_constant_size": "max_immediate_size"}


def generate(WGT, alias, root):
    out = []
    w = out.append
    src = part(WGT, "texture/format.rs")
    i = src.index("impl Serialize for TextureFormat")
    body = src[i : src.index("TextureFormat::Astc { block, channel }", i)]
    pairs = re.findall(r'TextureFormat::(\w+) => "([^"]+)"', body)
    vsrc = part(WGT, "vertex.rs")
    j = vsrc.index("pub enum VertexFormat")
    vbody = vsrc[j : vsrc.index("\n}\n", j)]
    vnames = re.findall(r"^\s+([A-Z][A-Za-z0-9_]*) = \d+,", vbody, re.M)


    def vname(n):
        if n == "Unorm10_10_10_2":
            return "unorm10-10-10-2"
        if n == "Unorm8x4Bgra":
            return "unorm8x4-bgra"
        return n.lower()


    lim = part(WGT, "limits.rs")
    k = lim.index("pub struct Limits")
    lbody = lim[k : lim.index("\n}\n", k)]
    fields = re.findall(r"^    pub (\w+): (u32|u64),", lbody, re.M)

    out = []
    w = out.append
    w("//! WebGPU's names for the open sets `krate:gpu` passes as strings: texture")
    w("//! formats, vertex formats, features and limits.")
    w("//!")
    w("//! Shared by the host (crates/runtime) and the guest wgpu backend")
    w("//! (crates/wgpu-krate), so the two can never spell a name differently.")
    w("//! Generated by scripts/gen-gpu-names.py from wgpu-types' own WebGPU name")
    w("//! tables; the names are WebGPU's, not wgpu's. Do not edit by hand.")
    w("")
    if root:
        w("#![no_std]")
        w("")
        w("extern crate alloc;")
        w("")
    w("use alloc::string::String;")
    w("use alloc::vec::Vec;")
    w(f"use {alias}::{{AstcBlock, AstcChannel, Features, Limits, TextureFormat, VertexFormat}};")
    w("")
    w('/// A texture format\'s WebGPU name ("rgba8unorm-srgb").')
    w("pub fn format_name(format: TextureFormat) -> String {")
    w("    let fixed = match format {")
    for v, n in pairs:
        w(f'        TextureFormat::{v} => "{n}",')
    w("        TextureFormat::Astc { block, channel } => {")
    w('            return alloc::format!(')
    w('                "astc-{}-{}",')
    w("                astc_block_name(block),")
    w("                astc_channel_name(channel)")
    w("            );")
    w("        }")
    w("    };")
    w("    String::from(fixed)")
    w("}")
    w("")
    w("/// The texture format a WebGPU name stands for.")
    w("pub fn parse_format(name: &str) -> Option<TextureFormat> {")
    w("    Some(match name {")
    for v, n in pairs:
        w(f'        "{n}" => TextureFormat::{v},')
    w("        _ => return parse_astc(name),")
    w("    })")
    w("}")
    w("")
    blocks = ["4x4", "5x4", "5x5", "6x5", "6x6", "8x5", "8x6", "8x8", "10x5", "10x6", "10x8", "10x10", "12x10", "12x12"]
    w("const ASTC_BLOCKS: [(AstcBlock, &str); 14] = [")
    for b in blocks:
        w(f'    (AstcBlock::B{b}, "{b}"),')
    w("];")
    w("")
    w("fn astc_block_name(block: AstcBlock) -> &'static str {")
    w("    ASTC_BLOCKS")
    w("        .iter()")
    w("        .find(|(b, _)| *b == block)")
    w("        .map(|(_, n)| *n)")
    w('        .unwrap_or("4x4")')
    w("}")
    w("")
    w("fn astc_channel_name(channel: AstcChannel) -> &'static str {")
    w("    match channel {")
    w('        AstcChannel::Unorm => "unorm",')
    w('        AstcChannel::UnormSrgb => "unorm-srgb",')
    w('        AstcChannel::Hdr => "hdr",')
    w("    }")
    w("}")
    w("")
    w("fn parse_astc(name: &str) -> Option<TextureFormat> {")
    w('    let rest = name.strip_prefix("astc-")?;')
    w("    for (block, block_name) in ASTC_BLOCKS {")
    w("        if let Some(channel) = rest")
    w("            .strip_prefix(block_name)")
    w("            .and_then(|r| r.strip_prefix('-'))")
    w("        {")
    w("            let channel = match channel {")
    w('                "unorm" => AstcChannel::Unorm,')
    w('                "unorm-srgb" => AstcChannel::UnormSrgb,')
    w('                "hdr" => AstcChannel::Hdr,')
    w("                _ => return None,")
    w("            };")
    w("            return Some(TextureFormat::Astc { block, channel });")
    w("        }")
    w("    }")
    w("    None")
    w("}")
    w("")
    w('/// A vertex format\'s WebGPU name ("float32x3").')
    w("pub fn vertex_format_name(format: VertexFormat) -> &'static str {")
    w("    match format {")
    for v in vnames:
        w(f'        VertexFormat::{v} => "{vname(v)}",')
    w("    }")
    w("}")
    w("")
    w("/// The vertex format a WebGPU name stands for.")
    w("pub fn parse_vertex_format(name: &str) -> Option<VertexFormat> {")
    w("    Some(match name {")
    for v in vnames:
        w(f'        "{vname(v)}" => VertexFormat::{v},')
    w("        _ => return None,")
    w("    })")
    w("}")
    w("")
    if root:
        w('/// Every feature in a set, by its WebGPU (or "wgpu-") name.')
        w("pub fn feature_names(features: Features) -> Vec<&'static str> {")
        w("    features.iter().filter_map(|f| f.as_str()).collect()")
        w("}")
        w("")
        w("/// The feature a name stands for.")
        w("pub fn parse_feature(name: &str) -> Option<Features> {")
        w("    name.parse::<Features>().ok()")
        w("}")
    else:
        # Older wgpu-types have no feature names; take the workspace's names
        # for every flag this version also has.
        names29 = part(source(VERSION), "features.rs")
        named = re.findall(
            r'#\[name\(((?:"[^"]+",?\s*)+)\)\]\s*(?:#\[[^\]]*\]\s*)*const (\w+)', names29
        )
        own = part(WGT, "features.rs")
        rows = []
        for strs, flag in named:
            # The flag under this version's own name: wgpu 28 renamed a few.
            older = OLDER_FEATURE.get(flag, flag)
            if re.search(r"^\s*const %s\b" % older, own, re.M):
                for n in re.findall(r'"([^"]+)"', strs):
                    rows.append((older, n))
        w("/// Each feature's WebGPU (or \"wgpu-\") names; the first is what it is called.")
        w("const FEATURE_NAMES: &[(Features, &str)] = &[")
        for flag, n in rows:
            w(f'    (Features::{flag}, "{n}"),')
        w("];")
        w("")
        w('/// Every feature in a set, by its WebGPU (or "wgpu-") name.')
        w("pub fn feature_names(features: Features) -> Vec<&'static str> {")
        w("    let mut out: Vec<&'static str> = Vec::new();")
        w("    for (flag, name) in FEATURE_NAMES {")
        w("        if features.contains(*flag) && !out.iter().any(|n| FEATURE_NAMES.iter().any(|(f, m)| f == flag && m == n)) {")
        w("            out.push(name);")
        w("        }")
        w("    }")
        w("    out")
        w("}")
        w("")
        w("/// The feature a name stands for.")
        w("pub fn parse_feature(name: &str) -> Option<Features> {")
        w("    FEATURE_NAMES.iter().find(|(_, n)| *n == name).map(|(f, _)| *f)")
        w("}")
    w("")
    w("/// A limit's getter and setter, by name.")
    w("pub type LimitAccess = (&'static str, fn(&Limits) -> u64, fn(&mut Limits, u64));")
    w("")
    w("/// Every limit wgpu knows, by its kebab-case WebGPU name. A limit is carried")
    w("/// as a u64 whatever its width; a u32 limit saturates.")
    w("pub const LIMITS: &[LimitAccess] = &[")
    for f, t in fields:
        n = (f if root else NEWER_LIMIT.get(f, f)).replace("_", "-")
        conv = "v" if t == "u64" else "v.min(u32::MAX as u64) as u32"
        getter = f"l.{f}" if t == "u64" else f"l.{f} as u64"
        w(f"    (\"{n}\", |l| {getter}, |l, v| l.{f} = {conv}),")
    w("];")
    w("")
    w("/// A set of limits as (name, value) pairs.")
    w("pub fn limit_pairs(limits: &Limits) -> Vec<(&'static str, u64)> {")
    w("    LIMITS")
    w("        .iter()")
    w("        .map(|(name, get, _)| (*name, get(limits)))")
    w("        .collect()")
    w("}")
    w("")
    w("/// Set one limit by name. False when the name is unknown.")
    w("pub fn set_limit(limits: &mut Limits, name: &str, value: u64) -> bool {")
    w("    match LIMITS.iter().find(|(n, _, _)| *n == name) {")
    w("        Some((_, _, set)) => {")
    w("            set(limits, value);")
    w("            true")
    w("        }")
    w("        None => false,")
    w("    }")
    w("}")
    w("")
    if root:
        w("/// The same tables for wgpu-types 27, for programs on wgpu 27 (IC-931).")
        w('#[cfg(feature = "wgpu-27")]')
        w("pub mod wgpu27;")
        w("")
    w("#[cfg(test)]")
    w("mod tests {")
    w("    use super::*;")
    w("")
    w("    #[test]")
    w("    fn every_format_name_reads_back_as_its_format() {")
    w("        let mut formats: Vec<TextureFormat> = alloc::vec![")
    for v, n in pairs:
        w(f"            TextureFormat::{v},")
    w("        ];")
    w("        for (block, _) in ASTC_BLOCKS {")
    w("            for channel in [AstcChannel::Unorm, AstcChannel::UnormSrgb, AstcChannel::Hdr] {")
    w("                formats.push(TextureFormat::Astc { block, channel });")
    w("            }")
    w("        }")
    w("        for format in formats {")
    w('            assert_eq!(parse_format(&format_name(format)), Some(format), "{format:?}");')
    w("        }")
    w('        assert_eq!(format_name(TextureFormat::Rgba8UnormSrgb), "rgba8unorm-srgb");')
    w('        assert_eq!(parse_format("rgba8-unorm"), None);')
    w("    }")
    w("")
    w("    #[test]")
    w("    fn vertex_formats_and_features_and_limits_round_trip() {")
    w('        assert_eq!(parse_vertex_format("float32x3"), Some(VertexFormat::Float32x3));')
    w('        assert_eq!(vertex_format_name(VertexFormat::Unorm8x4Bgra), "unorm8x4-bgra");')
    w("        assert_eq!(")
    w('            parse_feature("texture-compression-bc"),')
    w("            Some(Features::TEXTURE_COMPRESSION_BC)")
    w("        );")
    w("        let mut limits = Limits::default();")
    w('        assert!(set_limit(&mut limits, "max-bind-groups", 6));')
    w("        assert_eq!(limits.max_bind_groups, 6);")
    w('        assert!(!set_limit(&mut limits, "max-bind-group", 6));')
    w('        assert!(limit_pairs(&limits).contains(&("max-texture-dimension-2d", 8192)));')
    w("    }")
    w("}")
    return "\n".join(out) + "\n"


def formatted(text):
    """rustfmt the tables, as the tree is formatted; the check compares
    formatted with formatted."""
    import subprocess

    # From stdin, so rustfmt formats this text alone and does not go
    # looking for the files its `mod` lines name.
    done = subprocess.run(
        ["rustfmt", "--edition", "2021", "--emit", "stdout"],
        input=text, capture_output=True, text=True, check=True,
    )
    return done.stdout


# The workspace's wgpu-types (the host and wgpu 29 programs), and wgpu-types
# 27 for programs on wgpu 27 (Veloren), as the `wgpu27` module.
WGPU27_TYPES = re.search(r'^wgt27 = \{ package = "wgpu-types", version = "([^"]+)"', MANIFEST, re.M).group(1)
FILES = [
    (TARGET, formatted(generate(source(VERSION), "wgt", True))),
    (os.path.join(os.path.dirname(TARGET), "wgpu27.rs"),
     formatted(generate(source(WGPU27_TYPES), "wgt27", False))),
]
for path, text in FILES:
    rel = os.path.relpath(path, ROOT)
    if CHECK:
        if open(path).read() != text:
            sys.exit("%s is not what scripts/gen-gpu-names.py writes" % rel)
    else:
        open(path, "w").write(text)
print("gpu names are current" if CHECK else "wrote %s" % ", ".join(os.path.relpath(p, ROOT) for p, _ in FILES))
